package com.flower.spirit.config;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Properties;

import org.junit.jupiter.api.Test;

class PostgresqlDeploymentContractTest {

    @Test
    void latestImageCanRunMigrationAndSelectDatabaseProfileFromEnvironment() throws Exception {
        String dockerfile = Files.readString(
                Path.of("src", "main", "docker", "buildx", "Dockerfile"), StandardCharsets.UTF_8);

        assertThat(dockerfile)
                .contains("\"psycopg[binary]\"")
                .contains("ENV SPRING_PROFILES_ACTIVE=docker")
                .doesNotContain("--spring.profiles.active=docker");
    }

    @Test
    void postgresqlProfileOverridesSqliteConnectionInitializer() throws Exception {
        Properties docker = new Properties();
        try (var input = Files.newInputStream(
                Path.of("src", "main", "resources", "application-docker.properties"))) {
            docker.load(input);
        }
        Properties postgresql = new Properties();
        try (var input = Files.newInputStream(
                Path.of("src", "main", "resources", "application-postgresql.properties"))) {
            postgresql.load(input);
        }

        String property = "spring.datasource.hikari.connection-init-sql";
        assertThat(docker.getProperty(property)).startsWith("PRAGMA");
        assertThat(postgresql).containsKey(property);
        assertThat(postgresql.getProperty(property)).isEqualTo("SELECT 1");
    }

    @Test
	void longEntityIdentifiersUseBigintIdentityColumns() throws Exception {
		String baseline = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V001__baseline.sql"), StandardCharsets.UTF_8);

        for (String table : List.of("biz_collect_run", "biz_collect_run_event", "biz_collect_run_item",
                "biz_database_maintenance_operation", "biz_job_queue")) {
            assertThat(baseline).as(table).contains(
                    "CREATE TABLE " + table + " (\n    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
		}
	}

	@Test
	void integerNativeIdentityEntitiesUseIdentityColumns() throws Exception {
		String baseline = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V001__baseline.sql"), StandardCharsets.UTF_8);
		String detailEntity = Files.readString(Path.of("src", "main", "java", "com", "flower", "spirit",
				"entity", "CollectDataDetailEntity.java"), StandardCharsets.UTF_8);

		for (String table : List.of("biz_author_enrichment_job", "biz_author_name_history", "biz_author_profile",
				"biz_graphic_content", "biz_video")) {
			assertThat(baseline).as(table).contains(
					"CREATE TABLE " + table + " (\n    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
		}
		assertThat(baseline).as("biz_collect_data_detail V001 checksum must remain stable")
				.contains("CREATE TABLE biz_collect_data_detail (\n    id INTEGER PRIMARY KEY");
		assertThat(detailEntity)
				.contains("@GeneratedValue(strategy = GenerationType.IDENTITY)")
				.doesNotContain("@TableGenerator");
	}

	@Test
	void collectDetailIdentityMigrationIsSafeForExistingPostgresqlDatabases() throws Exception {
		String migration = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V002__collect_detail_identity.sql"), StandardCharsets.UTF_8);

		assertThat(migration)
				.contains("table_name = 'biz_collect_data_detail'")
				.contains("is_identity = 'YES'")
				.contains("ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
				.contains("pg_get_serial_sequence('biz_collect_data_detail', 'id')")
				.contains("SELECT MAX(id) FROM biz_collect_data_detail")
				.contains("EXISTS (SELECT 1 FROM biz_collect_data_detail)");
	}

	@Test
	void collectBackfillAndRemoteAccountMigrationIsSafeForExistingPostgresqlDatabases() throws Exception {
		String baseline = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V001__baseline.sql"), StandardCharsets.UTF_8);
		String migration = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V003__collect_backfill_and_remote_account_state.sql"), StandardCharsets.UTF_8);

		assertThat(baseline)
				.as("applied V001 migration must remain unchanged")
				.doesNotContain("backfill_cursor")
				.doesNotContain("remote_account_state");
		assertThat(migration)
				.contains("ALTER TABLE biz_collect_data")
				.contains("ADD COLUMN IF NOT EXISTS backfill_cursor VARCHAR(64)")
				.contains("ADD COLUMN IF NOT EXISTS backfill_complete INTEGER NOT NULL DEFAULT 0")
				.contains("ADD COLUMN IF NOT EXISTS backfill_verifying INTEGER NOT NULL DEFAULT 0")
				.contains("ADD COLUMN IF NOT EXISTS backfill_clean_passes INTEGER NOT NULL DEFAULT 0")
				.contains("ADD COLUMN IF NOT EXISTS remote_account_state VARCHAR(32)")
				.contains("ADD COLUMN IF NOT EXISTS remote_account_reason VARCHAR(255)")
				.contains("ADD COLUMN IF NOT EXISTS remote_account_detected_at TIMESTAMP");
	}

	@Test
	void collectBackfillDefaultsAreRepairedForExistingPostgresqlDatabases() throws Exception {
		String migration = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V004__repair_collect_backfill_defaults.sql"), StandardCharsets.UTF_8);

		assertThat(migration)
				.contains("COALESCE(backfill_complete, 0)")
				.contains("COALESCE(backfill_verifying, 0)")
				.contains("COALESCE(backfill_clean_passes, 0)")
				.contains("ALTER COLUMN backfill_complete SET DEFAULT 0")
				.contains("ALTER COLUMN backfill_complete SET NOT NULL")
				.contains("ALTER COLUMN backfill_verifying SET DEFAULT 0")
				.contains("ALTER COLUMN backfill_verifying SET NOT NULL")
				.contains("ALTER COLUMN backfill_clean_passes SET DEFAULT 0")
				.contains("ALTER COLUMN backfill_clean_passes SET NOT NULL");
	}

	@Test
	void downloadHistoryVisibilityMigrationPreservesQueueAuditRows() throws Exception {
		String migration = Files.readString(Path.of("src", "main", "resources", "db", "migration",
				"postgresql", "V005__add_download_history_visibility.sql"), StandardCharsets.UTF_8);

		assertThat(migration).contains("CREATE TABLE biz_download_history_hidden",
				"record_key VARCHAR(80) PRIMARY KEY", "source_type VARCHAR(32) NOT NULL",
				"source_id BIGINT NOT NULL", "idx_download_history_hidden_source");
	}

	@Test
	void mainJavaSqlAvoidsBareNullableParameterChecks() throws Exception {
		StringBuilder sources = new StringBuilder();
		try (var stream = Files.walk(Path.of("src", "main", "java"))) {
			for (Path source : stream.filter(path -> path.toString().endsWith(".java")).toList()) {
				sources.append(Files.readString(source, StandardCharsets.UTF_8)).append('\n');
			}
		}

		assertThat(sources.toString()).doesNotContain("? IS NOT NULL");
	}

	@Test
	void dynamicMediaFieldsAreExpandedByAForwardOnlyPostgresqlMigration() throws Exception {
		Path migrationRoot = Path.of("src", "main", "resources", "db", "migration", "postgresql");
		String baseline = Files.readString(migrationRoot.resolve("V001__baseline.sql"), StandardCharsets.UTF_8);
		String migration = Files.readString(migrationRoot.resolve(
				"V006__expand_dynamic_media_fields.sql"), StandardCharsets.UTF_8);
		String videoEntity = Files.readString(Path.of("src", "main", "java", "com", "flower", "spirit",
				"entity", "VideoDataEntity.java"), StandardCharsets.UTF_8).replace("\r\n", "\n");
		String graphicEntity = Files.readString(Path.of("src", "main", "java", "com", "flower", "spirit",
				"entity", "GraphicContentEntity.java"), StandardCharsets.UTF_8).replace("\r\n", "\n");

		assertThat(baseline).as("applied V001 checksum must retain the original column definitions")
				.contains("videoaddr VARCHAR(255), videocover VARCHAR(255)",
						"images TEXT, markroute VARCHAR(255), originaladdress VARCHAR(255)");
		assertThat(migration)
				.contains("ALTER TABLE biz_video", "ALTER COLUMN videoaddr TYPE TEXT",
						"ALTER COLUMN videocover TYPE TEXT", "ALTER COLUMN videounrealaddr TYPE TEXT",
						"ALTER COLUMN originaladdress TYPE TEXT", "ALTER COLUMN sourceurl TYPE TEXT",
						"ALTER COLUMN authoravatar TYPE TEXT", "ALTER TABLE biz_graphic_content",
						"ALTER COLUMN markroute TYPE TEXT")
				.doesNotContain("DROP TABLE", "DELETE FROM", "TRUNCATE");
		assertThat(videoEntity).contains("@Column(columnDefinition = \"TEXT\")\n\tprivate String videocover;",
				"@Column(columnDefinition = \"TEXT\")\n\tprivate String sourceurl;");
		assertThat(graphicEntity).contains("@Column(columnDefinition = \"TEXT\")\n\tprivate String markroute;",
				"@Column(columnDefinition = \"TEXT\")\n\tprivate String authoravatar;");
	}

	@Test
	void collectDownloadsCanPersistAForwardOnlyMetadataSnapshot() throws Exception {
		Path migrationRoot = Path.of("src", "main", "resources", "db", "migration", "postgresql");
		String baseline = Files.readString(migrationRoot.resolve("V001__baseline.sql"), StandardCharsets.UTF_8);
		String migration = Files.readString(migrationRoot.resolve(
				"V007__add_collect_download_metadata_snapshot.sql"), StandardCharsets.UTF_8);

		assertThat(baseline).as("applied V001 checksum must remain unchanged")
				.doesNotContain("metadata_snapshot");
		assertThat(migration)
				.contains("ALTER TABLE biz_collect_run_item")
				.contains("ADD COLUMN IF NOT EXISTS metadata_snapshot TEXT")
				.doesNotContain("DROP TABLE", "DELETE FROM", "TRUNCATE");
	}
}
